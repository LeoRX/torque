#!/bin/sh
# entrypoint.sh — generates creds.php from environment variables at container start,
# then hands control to the CMD (apache2-foreground).
set -e

# Require the mandatory DB credentials — either as plain env vars or as
# Docker secrets via the *_FILE convention (e.g. DB_PASS_FILE=/run/secrets/db_pass).
if { [ -z "${DB_USER}" ] && [ -z "${DB_USER_FILE}" ]; } || { [ -z "${DB_PASS}" ] && [ -z "${DB_PASS_FILE}" ]; }; then
    echo "ERROR: DB_USER and DB_PASS (or DB_USER_FILE / DB_PASS_FILE) are required." >&2
    exit 1
fi
for _f in "${DB_USER_FILE}" "${DB_PASS_FILE}" "${APP_USER_FILE}" "${APP_PASS_FILE}" \
          "${BEARER_TOKEN_FILE}" "${TORQUE_ID_FILE}" "${TORQUE_ID_HASH_FILE}"; do
    if [ -n "$_f" ] && ! su -s /bin/sh www-data -c "test -r '$_f'" 2>/dev/null; then
        echo "WARNING: secret file $_f is not readable by www-data — the app will not see it." >&2
    fi
done

# Generate /var/www/html/creds.php. The heredoc is QUOTED ('PHP') so the shell
# substitutes nothing: values are read at request time. Pasting env values into
# PHP source broke on any quote/backslash in a password and allowed PHP code
# injection via DB_PORT and friends.
cat > /var/www/html/creds.php << 'PHP'
<?php
// Auto-generated by entrypoint.sh — do not edit.
// Values come from the container environment (docker-compose.yml / .env).
// Each secret can also be supplied as a file via NAME_FILE (Docker secrets),
// which keeps it out of `docker inspect` and /proc/*/environ.

if (!function_exists('torque_env')) {
    function torque_env(string $name, string $default = ''): string {
        $file = getenv($name . '_FILE');
        if ($file !== false && $file !== '') {
            $v = @file_get_contents($file);
            if ($v !== false) {
                return rtrim($v, "\r\n");
            }
            error_log("creds.php: cannot read {$name}_FILE ({$file})");
            return $default;
        }
        $v = getenv($name);
        return ($v === false || $v === '') ? $default : $v;
    }
}

$db_host           = torque_env('DB_HOST', 'host.docker.internal');
$db_user           = torque_env('DB_USER');
$db_pass           = torque_env('DB_PASS');
$db_port           = (int)torque_env('DB_PORT', '3306');
$db_name           = torque_env('DB_NAME', 'torque');
$db_table          = 'raw_logs';
$db_keys_table     = 'torque_keys';
$db_sessions_table = 'sessions';
$torque_id         = torque_env('TORQUE_ID');
$torque_id_hash    = torque_env('TORQUE_ID_HASH');
$bearer_token      = torque_env('BEARER_TOKEN');

// Web login users (legacy array — new accounts should use the torque_users DB table)
$users = [];
if (torque_env('APP_USER') !== '' && torque_env('APP_PASS') !== '') {
    $users[] = ['user' => torque_env('APP_USER'), 'pass' => torque_env('APP_PASS')];
}
PHP

chown www-data:www-data /var/www/html/creds.php
chmod 600 /var/www/html/creds.php

echo "entrypoint: creds.php generated (reads environment / *_FILE secrets at runtime)."

# ── In-container GPS repair scheduler ─────────────────────────────────────────
# A short loop calls scheduler_tick.php, which reads the cadence/on-off from the
# Settings page (gps_repair_cron + gps_repair_interval) and runs gps/repair.php
# only when the interval has elapsed. So the schedule is DB-controlled — no host
# cron and no container restart needed to change it. GPS_REPAIR_CRON=0 is an
# ops-level hard kill that stops the loop entirely. GPS_REPAIR_TICK tunes how
# often the loop checks (seconds, default 300). Output → container stdout.
if [ "${GPS_REPAIR_CRON:-1}" != "0" ]; then
    GPS_REPAIR_TICK="${GPS_REPAIR_TICK:-300}"
    echo "entrypoint: in-container GPS repair scheduler enabled (tick ${GPS_REPAIR_TICK}s; cadence set in Settings)."
    (
        # Let Apache and the DB settle before the first tick
        sleep 60
        while true; do
            php /var/www/html/gps/scheduler_tick.php 2>&1 | sed 's/^/[gps-repair] /' || true
            sleep "${GPS_REPAIR_TICK}"
        done
    ) &
else
    echo "entrypoint: in-container GPS repair scheduler hard-disabled (GPS_REPAIR_CRON=0)."
fi

exec "$@"
