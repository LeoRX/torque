#!/bin/sh
# entrypoint.sh — generates creds.php from environment variables at container start,
# then hands control to the CMD (apache2-foreground).
set -e

# Require the mandatory DB credentials
if [ -z "${DB_USER}" ] || [ -z "${DB_PASS}" ]; then
    echo "ERROR: DB_USER and DB_PASS environment variables are required." >&2
    exit 1
fi

# Generate /var/www/html/creds.php. The heredoc is QUOTED ('PHP') so the shell
# substitutes nothing: values are read with getenv() at request time. Pasting
# env values into PHP source broke on any quote/backslash in a password and
# allowed PHP code injection via DB_PORT and friends.
cat > /var/www/html/creds.php << 'PHP'
<?php
// Auto-generated by entrypoint.sh — do not edit.
// Values come from the container environment (docker-compose.yml / .env).

$db_host           = getenv('DB_HOST') ?: 'host.docker.internal';
$db_user           = (string)getenv('DB_USER');
$db_pass           = (string)getenv('DB_PASS');
$db_port           = (int)(getenv('DB_PORT') ?: 3306);
$db_name           = getenv('DB_NAME') ?: 'torque';
$db_table          = 'raw_logs';
$db_keys_table     = 'torque_keys';
$db_sessions_table = 'sessions';
$torque_id         = (string)getenv('TORQUE_ID');
$torque_id_hash    = (string)getenv('TORQUE_ID_HASH');
$bearer_token      = (string)getenv('BEARER_TOKEN');

// Web login users (legacy array — new accounts should use the torque_users DB table)
$users = [];
if (getenv('APP_USER') !== false && getenv('APP_USER') !== ''
    && getenv('APP_PASS') !== false && getenv('APP_PASS') !== '') {
    $users[] = ['user' => getenv('APP_USER'), 'pass' => getenv('APP_PASS')];
}
PHP

chown www-data:www-data /var/www/html/creds.php
chmod 600 /var/www/html/creds.php

echo "entrypoint: creds.php generated from environment variables."

# ── In-container GPS repair scheduler ─────────────────────────────────────────
# A short loop calls scheduler_tick.php, which reads the cadence/on-off from the
# Settings page (gps_repair_cron + gps_repair_interval) and runs gps/repair.php
# only when the interval has elapsed. So the schedule is DB-controlled — no host
# cron and no container restart needed to change it. GPS_REPAIR_CRON=0 is an
# ops-level hard kill that stops the loop entirely. GPS_REPAIR_TICK tunes how
# often the loop checks (seconds, default 300). Output → container stdout.
if [ "${GPS_REPAIR_CRON:-1}" != "0" ]; then
    GPS_REPAIR_TICK="${GPS_REPAIR_TICK:-300}"
    echo "entrypoint: in-container GPS repair scheduler enabled (tick ${GPS_REPAIR_TICK}s; cadence set in Settings)."
    (
        # Let Apache and the DB settle before the first tick
        sleep 60
        while true; do
            php /var/www/html/gps/scheduler_tick.php 2>&1 | sed 's/^/[gps-repair] /' || true
            sleep "${GPS_REPAIR_TICK}"
        done
    ) &
else
    echo "entrypoint: in-container GPS repair scheduler hard-disabled (GPS_REPAIR_CRON=0)."
fi

exec "$@"
